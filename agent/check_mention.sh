#!/usr/bin/env bash
# ТЗ-44 L1: коммит, обещающий правку стража сообщением, обязан её нести.
#
# Причина (измерено, раунд 48): правка agent/p6_rule.sh три раза
# исчезала по дороге в коммит — уборка теста I5 возвращает файл из
# индекса/HEAD, и коммит с сообщением про страж приезжал пустым.
# Барьер: если ТЕМА сообщения коммита называет файл стража (p1_rule.sh /
# p6_rule.sh, без учёта регистра), этот файл обязан быть в составе
# коммита. Иначе — красный с именем файла. Темой — с ТЗ-103 N1.
#
# ТЗ-102 M2: матч по ИМЕНИ ФАЙЛА, а не по голому токену. Прежний шаблон
# «(^|не-буква)p1(не-буква|$)» ловил каждое упоминание правила протокола
# P1: круг 137 показал честное сообщение «(P1: удалённых 0)» без правки
# стража, окрашенное барьером, — страж не обязан ехать в коммите, который
# его не касается. Имя файла — ровно то, о чём говорит шапка скрипта.
#
# ТЗ-103 N1 (решение координатора, вариант (a)): смотрим только ТЕМУ —
# первую строку сообщения. Обещание живёт в теме; имя стража в теле —
# цитата, ссылка на то, что уже было. Измерено на published M1 (49c6320):
# в теме имени стража нет, в теле строкой «красный до правки зуб на страж
# agent/p1_rule.sh из I5» описывается след неотслеживаемого файла, и этот
# коммит барьер красил — пока HEAD, краснел и весь selfcheck. git revert
# копирует тему отменяемого коммита, поэтому отмена правки стража остаётся
# покрытой: обещание в теме — страж в составе.
#
# Аргументы: $1 = файл сообщения, $2 = файл со списком путей коммита.
# Запуск: bash agent/check_mention.sh <msg> <files>  (0 = зелёный).
set -u

msg_file="$1"
files_file="$2"
subject="$(head -n 1 "$msg_file" 2>/dev/null)"

for g in p1 p6; do
    guard="agent/${g}_rule.sh"
    if printf '%s\n' "$subject" | grep -qiE "${g}_rule\.sh"; then
        if ! grep -qxF "$guard" "$files_file" 2>/dev/null; then
            echo "L1: тема сообщения называет $guard, а стража в" \
                 "составе коммита нет"
            exit 1
        fi
    fi
done
exit 0
