#!/usr/bin/env bash
# ТЗ-44 L1: коммит, обещающий правку стража сообщением, обязан её нести.
#
# Причина (измерено, раунд 48): правка agent/p6_rule.sh три раза
# исчезала по дороге в коммит — уборка теста I5 возвращает файл из
# индекса/HEAD, и коммит с сообщением про «p6» приезжал пустым.
# Барьер: если сообщение коммита упоминает p1_rule.sh / p6_rule.sh
# (словом, без учёта регистра), соответствующий файл обязан быть в
# составе коммита. Иначе — красный с именем файла.
#
# Аргументы: $1 = файл сообщения, $2 = файл со списком путей коммита.
# Запуск: bash agent/check_mention.sh <msg> <files>  (0 = зелёный).
set -u

msg_file="$1"
files_file="$2"

for g in p1 p6; do
    guard="agent/${g}_rule.sh"
    if grep -qiE "(^|[^a-zA-Z0-9_])${g}([^a-zA-Z0-9_]|$)" "$msg_file" 2>/dev/null; then
        if ! grep -qxF "$guard" "$files_file" 2>/dev/null; then
            echo "L1: сообщение называет $guard, но страж не в составе коммита"
            exit 1
        fi
    fi
done
exit 0
